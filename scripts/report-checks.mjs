import assert from 'node:assert/strict';
export async function runReportChecks({request,status,account,admin,seller,buyer,book,suffix}) {
  const call = async(path,method='GET',json,cookie=admin.cookie,expected=200,headers) => status(await request(path,{method,json,cookie,headers}),expected);
  const make = async() => {
    const {id}=(await call('/api/listings','POST',{...book,title:`Report fixture ${suffix}`},seller.cookie,201)).data;
    await call(`/api/admin/listings/${id}/decision`,'POST',{decision:'active',version:0},admin.cookie);
    return id;
  };
  const id=await make(), path=`/api/listings/${id}/reports`, payload={reason:'fraud',description:'Nội dung báo cáo thử nghiệm cần được kiểm tra.'};
  await call(path,'POST',payload,null,401);
  await call(path,'POST',payload,seller.cookie,400);
  await call(path,'POST',payload,buyer.cookie,403,{Origin:'https://evil.example'});
  await call(path,'POST',payload,buyer.cookie,403,{'Sec-Fetch-Site':'cross-site'});
  status(await request(path,{method:'POST',cookie:buyer.cookie,body:'plain'}),415);
  for (const data of [{...payload,reason:'unknown'},{...payload,reason:['fraud']},{...payload,description:'short'},{...payload,description:' '.repeat(20)},{...payload,description:'x'.repeat(1001)},{...payload,description:'😀'.repeat(5)}]) await call(path,'POST',data,buyer.cookie,400);
  await call('/api/listings/unknown/reports','POST',payload,buyer.cookie,404);
  await call('/api/listings/unknown/reports','POST',payload,buyer.cookie,403,{Origin:'https://foreign.example','Sec-Fetch-Site':'same-site'});
  await call('/api/listings/unknown/reports','POST',payload,buyer.cookie,404,{Origin:'http://127.0.0.1:5173','Sec-Fetch-Site':'same-origin'});
  const concurrent=await Promise.all([1,2].map(()=>request(path,{method:'POST',cookie:buyer.cookie,json:payload})));
  assert.deepEqual(concurrent.map(x=>x.response.status).sort(),[201,409]);
  await call(path,'POST',payload,buyer.cookie,409);
  await call('/api/admin/reports','GET',undefined,null,401);
  await call('/api/admin/reports','GET',undefined,buyer.cookie,403);
  await call(`/api/listings/${id}`,'GET',undefined,null,200);
  const rows = async(status='all',cookie=admin.cookie) => (await call(`/api/admin/reports?status=${status}`,'GET',undefined,cookie)).data.items;
  let report=(await rows()).find(x=>x.listing_id===id);
  assert.equal(report.status,'pending');assert.equal(report.description,payload.description);
  const list=await call('/api/admin/reports');assert.match(list.response.headers.get('cache-control'),/private, no-store/);
  assert.ok(!JSON.stringify(list.data).includes(buyer.email));
  await call('/api/admin/reports?status=bad','GET',undefined,admin.cookie,400);
  await call(`/api/admin/reports/${report.id}`,'GET',undefined,buyer.cookie,404);
  const decision=`/api/admin/reports/${report.id}/decision`;
  const action={action:'hide',note:'Xác nhận nội dung vi phạm.',version:report.version,listing_version:report.current_listing_version};
  await call(decision,'POST',action,buyer.cookie,403);
  const staff=await account('report-staff');
  const grant=async permissions => {
    const role=(await call('/api/admin/roles','POST',{name:`Report ${suffix} ${permissions.length}`,permissions},admin.cookie,201)).data;
    const row=(await call(`/api/admin/users?q=${encodeURIComponent(staff.email)}`)).data.items.find(x=>x.id===staff.id);
    await call(`/api/admin/users/${staff.id}/roles`,'PUT',{role_ids:[role.id],version:row.version},admin.cookie);
  };
  await grant(['reports.view']);
  await rows('pending',staff.cookie);
  await call(decision,'POST',action,staff.cookie,403);
  await grant(['reports.view','reports.review']);
  await call(decision,'POST',action,staff.cookie,403);
  await call(decision,'POST',{...action,action:'dismiss',note:'   '},staff.cookie,400);
  await call(decision,'POST',{...action,action:'dismiss',note:'x'.repeat(501)},staff.cookie,400);
  await call(decision,'POST',{...action,version:99},admin.cookie,409);
  await call(decision,'POST',{...action,listing_version:99},admin.cookie,409);
  assert.equal((await rows()).find(x=>x.id===report.id).status,'pending');
  await call(`/api/listings/${id}`,'GET',undefined,null,200);
  await call(decision,'POST',action,admin.cookie,200);
  await call(`/api/listings/${id}`,'GET',undefined,null,404);
  await call(`/api/listings/${id}/contact`,'GET',undefined,buyer.cookie,404);
  await call(decision,'POST',action,admin.cookie,409);
  report=(await rows()).find(x=>x.id===report.id);assert.equal(report.status,'resolved');assert.equal(report.resolution,'hide');assert.equal(report.review_note,action.note);assert.ok(report.reviewed_at);assert.equal(report.listing_status,'hidden');
  const audit=(await call('/api/admin/audit?limit=100')).data.items;
  assert.equal(audit.filter(x=>x.action==='reports.review' && x.resource_id===report.id).length,1);
  const own=(await call(`/api/seller/listings/${id}`,'GET',undefined,seller.cookie)).data.item;
  assert.equal(own.status,'hidden');
  // A terminal sold listing cannot be changed back to hidden while processing a report.
  const sold=await make();await call(`/api/listings/${sold}/reports`,'POST',payload,staff.cookie,201);
  let soldRow=(await call(`/api/seller/listings/${sold}`,'GET',undefined,seller.cookie)).data.item;
  await call(`/api/seller/listings/${sold}/status`,'POST',{status:'sold',version:soldRow.version},seller.cookie);
  const soldReport=(await rows()).find(x=>x.listing_id===sold);
  await call(`/api/admin/reports/${soldReport.id}/decision`,'POST',{...action,version:0,listing_version:soldReport.current_listing_version},admin.cookie,409);
  const finish={action:'dismiss',note:'Không đủ cơ sở; sách đã bán.',version:0};
  const race=await Promise.all([1,2].map(()=>request(`/api/admin/reports/${soldReport.id}/decision`,{method:'POST',cookie:staff.cookie,json:finish})));
  assert.deepEqual(race.map(x=>x.response.status).sort(),[200,409]);
  assert.equal((await rows()).find(x=>x.id===soldReport.id).status,'dismissed');
  // Per-user cap is atomic even when requests arrive concurrently.
  const limiter=await account('report-limit'), ids=await Promise.all(Array.from({length:6},()=>make()));
  const limited=await Promise.all(ids.map(id=>request(`/api/listings/${id}/reports`,{method:'POST',cookie:limiter.cookie,json:payload})));
  assert.equal(limited.filter(x=>x.response.status===201).length,5);assert.equal(limited.filter(x=>x.response.status===429).length,1);
  const limitedResponse=limited.find(x=>x.response.status===429);assert.equal(limitedResponse.response.headers.get('retry-after'),'3600');
  const uiListing=await make();
  console.log('PASS: reports auth/privacy, validation, duplicate/rate races, delegated rights, atomic hiding, sold terminal, audit and resolution races');
  return { listingId:uiListing, cookie:staff.cookie };
}
