    page.get_by_role('button',name='Lưu hồ sơ',exact=True).click()
    expect(page.get_by_text('Đã cập nhật hồ sơ',exact=True)).to_be_visible()
    page.reload(wait_until='networkidle');expect(name).to_have_value('CMS Profile QA')
    name.fill(previous);page.get_by_role('button',name='Lưu hồ sơ',exact=True).click()
