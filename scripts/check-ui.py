def forward_live(route):
 r=route.request
 if not r.url.startswith(origin+'/'):raise AssertionError('Unexpected external UI resource')
 headers={k:v for k,v in r.all_headers().items() if k.lower() not in {'host','content-length','accept-encoding'}};headers['Accept-Encoding']='identity'
 request=urllib.request.Request(r.url,data=r.post_data_buffer,method=r.method,headers=headers)
 try:response=urllib.request.urlopen(request,timeout=40)
 except urllib.error.HTTPError as e:response=e
 with response:
  body=response.read()
  if response.headers.get('Content-Encoding')=='gzip':body=gzip.decompress(body)
  headers={k:v for k,v in response.headers.items() if k.lower() not in {'content-length','transfer-encoding','content-encoding','connection'}}
  route.fulfill(status=response.status,headers=headers,body=body)
